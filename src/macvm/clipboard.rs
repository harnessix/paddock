//! The clipboard of a session, pure with Linux tests.
//!
//! The rule: the clipboard moves only while a session window is the key
//! window on the host. Host to guest: when a session window becomes key,
//! and on each change of the host pasteboard while it is key, the shim
//! sends the host content to the guest. Guest to host: a change of the
//! guest pasteboard while a session window is key sets the host pasteboard;
//! a change while it is not key does nothing. So the guest app never reads
//! what the user copies in other host windows, and the host never sees what
//! the guest app writes while the user is elsewhere.
//!
//! The item set crosses whole, each item with its types in the order of
//! [`TYPES`]; other types are left out. An item with the concealed or the
//! transient marker of a password manager is left out, and an item set
//! that a clipboard utility marked auto generated is not sent again. A
//! set of 64 KiB or less goes inline on the control line, a larger one
//! as a transfer, and over 16 MiB the images go first and then the set is
//! refused with the badge. A file URL crosses only when it points into a
//! share, translated to the other side's path.
//!
//! Before the filter, [`convert`] adds what the other side's apps expect:
//! an HTML item without plain text gets the text of the HTML, so a paste
//! into a plain text field works, and a TIFF item without PNG gets a PNG
//! through the platform's image library, so an app that takes only PNG
//! pastes it and so an image over the limit crosses as the smaller PNG or
//! not at all.

use super::proto::PasteItem;
use super::shares::{self, Share};
use super::text;
use base64::Engine as _;
use std::path::{Path, PathBuf};

/// The most bytes that go inline on the control line.
pub const INLINE_MAX: u64 = 64 * 1024;
/// The most bytes of one clipboard set.
pub const TRANSFER_MAX: u64 = super::files_port::TRANSFER_MAX;
/// The types that cross, in the order of preference.
pub const TYPES: [&str; 6] = [
    "public.utf8-plain-text",
    "public.rtf",
    "public.html",
    "public.png",
    "public.tiff",
    "public.file-url",
];
pub const TEXT: &str = "public.utf8-plain-text";
pub const HTML: &str = "public.html";
pub const PNG: &str = "public.png";
pub const TIFF: &str = "public.tiff";
pub const FILE_URL: &str = "public.file-url";
/// A password manager marks its item so: it never crosses.
pub const CONCEALED: &str = "org.nspasteboard.ConcealedType";
pub const TRANSIENT: &str = "org.nspasteboard.TransientType";
/// A clipboard utility marks a set it made from the last one so: it is
/// not sent again.
pub const AUTO_GENERATED: &str = "org.nspasteboard.AutoGeneratedType";
/// Every type the pasteboard readers ask for.
pub const READ_TYPES: [&str; 9] = [
    TYPES[0],
    TYPES[1],
    TYPES[2],
    TYPES[3],
    TYPES[4],
    TYPES[5],
    CONCEALED,
    TRANSIENT,
    AUTO_GENERATED,
];

/// One pasteboard item: its types with their bytes.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Item {
    pub types: Vec<(String, Vec<u8>)>,
}

impl Item {
    pub fn text(s: &str) -> Item {
        Item::default().with(TEXT, s.as_bytes())
    }

    pub fn with(mut self, uti: &str, data: &[u8]) -> Item {
        self.types.push((uti.to_string(), data.to_vec()));
        self
    }

    pub fn has(&self, uti: &str) -> bool {
        self.types.iter().any(|(t, _)| t == uti)
    }

    pub fn get(&self, uti: &str) -> Option<&[u8]> {
        self.types
            .iter()
            .find(|(t, _)| t == uti)
            .map(|(_, d)| d.as_slice())
    }

    pub fn size(&self) -> u64 {
        self.types.iter().map(|(_, d)| d.len() as u64).sum()
    }

    /// The wire form: the bytes as base64.
    pub fn to_wire(&self) -> PasteItem {
        PasteItem {
            types: self
                .types
                .iter()
                .map(|(t, d)| {
                    (
                        t.clone(),
                        base64::engine::general_purpose::STANDARD.encode(d),
                    )
                })
                .collect(),
        }
    }

    /// From the wire form, the types in the order of [`TYPES`] and the
    /// others after. A type whose base64 is bad is left out.
    pub fn from_wire(w: &PasteItem) -> Item {
        let mut item = Item::default();
        for (t, b64) in &w.types {
            if let Ok(d) = base64::engine::general_purpose::STANDARD.decode(b64) {
                item.types.push((t.clone(), d));
            }
        }
        let rank = |t: &str| TYPES.iter().position(|k| *k == t).unwrap_or(TYPES.len());
        item.types.sort_by_key(|(t, _)| rank(t));
        item
    }
}

pub fn to_wire(items: &[Item]) -> Vec<PasteItem> {
    items.iter().map(Item::to_wire).collect()
}

pub fn from_wire(items: &[PasteItem]) -> Vec<Item> {
    items.iter().map(Item::from_wire).collect()
}

/// A set that crosses.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Payload {
    pub items: Vec<Item>,
}

impl Payload {
    pub fn size(&self) -> u64 {
        self.items.iter().map(Item::size).sum()
    }

    /// True when the set fits on the control line.
    pub fn inline(&self) -> bool {
        self.size() <= INLINE_MAX
    }
}

/// What the host does after an event.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Action {
    SendToGuest(Payload),
    SetHost(Payload),
    Nothing,
    /// The set does not cross; the badge says why.
    Refuse(String),
}

/// Which way a set goes, for the file URLs.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Direction {
    ToGuest,
    ToHost,
}

/// The filter on an item set, before the translation:
/// the marked items out, the types in order, the rest left out, then the
/// size. `Ok(empty)` when nothing is left, `Err(badge)` over the limit.
pub fn prepare(items: &[Item]) -> Result<Vec<Item>, String> {
    if !items.is_empty() && items.iter().all(|i| i.has(AUTO_GENERATED)) {
        return Ok(Vec::new());
    }
    let mut out: Vec<Item> = items
        .iter()
        .filter(|i| !i.has(CONCEALED) && !i.has(TRANSIENT) && !i.has(AUTO_GENERATED))
        .map(|i| Item {
            types: TYPES
                .iter()
                .filter_map(|t| i.get(t).map(|d| (t.to_string(), d.to_vec())))
                .collect(),
        })
        .filter(|i| !i.types.is_empty())
        .collect();
    let size = |items: &[Item]| items.iter().map(Item::size).sum::<u64>();
    let total = size(&out);
    if total <= TRANSFER_MAX {
        return Ok(out);
    }
    // Over the limit: the images go, the largest format first, as long
    // as a text stays.
    let had_image = out.iter().any(|i| i.has(PNG) || i.has(TIFF));
    for drop in [TIFF, PNG] {
        if size(&out) <= TRANSFER_MAX {
            break;
        }
        for i in &mut out {
            i.types.retain(|(t, _)| t != drop);
        }
        out.retain(|i| !i.types.is_empty());
    }
    if out.is_empty() || size(&out) > TRANSFER_MAX {
        return Err(if had_image && out.iter().all(|i| !i.has(TEXT)) {
            text::image_too_large()
        } else {
            text::clipboard_too_large(total)
        });
    }
    Ok(out)
}

/// The conversions, before [`prepare`]: an HTML item
/// without plain text gets [`html_text`] as a second type, a TIFF item
/// without PNG gets the PNG that `tiff_to_png` makes (None when the bytes
/// are not an image the platform reads: the TIFF stays alone).
pub fn convert(
    mut items: Vec<Item>,
    tiff_to_png: &mut dyn FnMut(&[u8]) -> Option<Vec<u8>>,
) -> Vec<Item> {
    for i in &mut items {
        if !i.has(TEXT) {
            if let Some(html) = i.get(HTML).and_then(|d| std::str::from_utf8(d).ok()) {
                let text = html_text(html);
                if !text.is_empty() {
                    i.types.push((TEXT.to_string(), text.into_bytes()));
                }
            }
        }
        if !i.has(PNG) {
            if let Some(png) = i.get(TIFF).and_then(&mut *tiff_to_png) {
                i.types.push((PNG.to_string(), png));
            }
        }
    }
    items
}

/// The text of an HTML fragment: the tags go, `<br>` and the ends of the
/// block elements become line breaks, the common entities are decoded,
/// runs of blanks become one space, and the result is trimmed. Scripts
/// and styles go whole.
pub fn html_text(html: &str) -> String {
    let mut out = String::with_capacity(html.len());
    let mut rest = html;
    while let Some(lt) = rest.find('<') {
        push_text(&mut out, &rest[..lt]);
        rest = &rest[lt..];
        let Some(gt) = rest.find('>') else {
            // A tag that never closes: nothing after it is text.
            rest = "";
            break;
        };
        let tag = &rest[1..gt];
        rest = &rest[gt + 1..];
        let name: String = tag
            .trim_start_matches('/')
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect::<String>()
            .to_ascii_lowercase();
        let closing = tag.starts_with('/');
        if tag.starts_with("!--") {
            // A comment: skip to its end.
            if let Some(end) = rest.find("-->") {
                rest = &rest[end + 3..];
            }
            continue;
        }
        if !closing && matches!(name.as_str(), "script" | "style") {
            let close = format!("</{name}"); // not user text
            match rest.to_ascii_lowercase().find(&close) {
                Some(end) => {
                    rest = &rest[end..];
                    if let Some(gt) = rest.find('>') {
                        rest = &rest[gt + 1..];
                    }
                }
                None => rest = "",
            }
            continue;
        }
        let breaks = match name.as_str() {
            "br" | "hr" => true,
            "p" | "div" | "li" | "tr" | "h1" | "h2" | "h3" | "h4" | "h5" | "h6" | "ul" | "ol"
            | "table" | "blockquote" | "pre" | "section" | "article" | "header" | "footer"
            | "title" => closing,
            _ => false,
        };
        if breaks && !out.ends_with('\n') && !out.is_empty() {
            out.push('\n');
        }
    }
    push_text(&mut out, rest);
    let lines: Vec<String> = out.lines().map(|l| l.trim().to_string()).collect();
    let mut text = String::new();
    for l in lines {
        if l.is_empty() && text.ends_with('\n') {
            continue;
        }
        text.push_str(&l);
        text.push('\n');
    }
    text.trim().to_string()
}

/// Text between tags: the entities decoded and the blanks collapsed.
fn push_text(out: &mut String, raw: &str) {
    let mut rest = raw;
    let mut piece = String::with_capacity(raw.len());
    while let Some(amp) = rest.find('&') {
        piece.push_str(&rest[..amp]);
        rest = &rest[amp..];
        let semi = rest.find(';').filter(|i| *i <= 10);
        match semi.and_then(|i| entity(&rest[1..i]).map(|c| (c, i))) {
            Some((c, i)) => {
                piece.push(c);
                rest = &rest[i + 1..];
            }
            None => {
                piece.push('&');
                rest = &rest[1..];
            }
        }
    }
    piece.push_str(rest);
    let mut blank = out.ends_with(' ') || out.ends_with('\n') || out.is_empty();
    for c in piece.chars() {
        if c == '\u{a0}' || c.is_whitespace() {
            if !blank {
                out.push(' ');
                blank = true;
            }
        } else {
            out.push(c);
            blank = false;
        }
    }
}

/// The character of an HTML entity name, `amp` or `#x27`.
fn entity(name: &str) -> Option<char> {
    Some(match name {
        "amp" => '&',
        "lt" => '<',
        "gt" => '>',
        "quot" => '"',
        "apos" => '\'',
        "nbsp" => '\u{a0}',
        _ => {
            let digits = name.strip_prefix('#')?;
            let code = match digits.strip_prefix(['x', 'X']) {
                Some(hex) => u32::from_str_radix(hex, 16).ok()?,
                None => digits.parse().ok()?,
            };
            char::from_u32(code)?
        }
    })
}

/// The path of a `file://` URL, percent-decoded. None for another scheme
/// or a host other than the local one.
pub fn url_path(url: &str) -> Option<PathBuf> {
    let rest = url.strip_prefix("file://")?;
    let rest = rest.strip_prefix("localhost").unwrap_or(rest);
    if !rest.starts_with('/') {
        return None;
    }
    let mut bytes = Vec::with_capacity(rest.len());
    let b = rest.as_bytes();
    let mut i = 0;
    while i < b.len() {
        if b[i] == b'%' {
            if i + 2 >= b.len() {
                return None;
            }
            let hex = std::str::from_utf8(&b[i + 1..i + 3]).ok()?;
            bytes.push(u8::from_str_radix(hex, 16).ok()?);
            i += 3;
        } else {
            bytes.push(b[i]);
            i += 1;
        }
    }
    let s = String::from_utf8(bytes).ok()?;
    let s = s.split('?').next().unwrap_or("");
    Some(PathBuf::from(s.trim_end_matches('/')))
}

/// The `file://` URL of a path, with the bytes outside the unreserved set
/// percent-encoded.
pub fn path_url(path: &Path) -> String {
    use std::os::unix::ffi::OsStrExt;
    let mut s = String::from("file://");
    for &b in path.as_os_str().as_bytes() {
        let plain = b.is_ascii_alphanumeric() || b"-._~/".contains(&b);
        if plain {
            s.push(b as char);
        } else {
            s.push_str(&format!("%{b:02X}")); // not user text
        }
    }
    s
}

/// Translate the file URLs of a set across the shares; a URL that points
/// outside every share is left out, and an item with nothing left goes.
pub fn translate(items: Vec<Item>, shares: &[Share], dir: Direction) -> Vec<Item> {
    items
        .into_iter()
        .filter_map(|mut i| {
            i.types.retain_mut(|(t, d)| {
                if t != FILE_URL {
                    return true;
                }
                let Some(url) = std::str::from_utf8(d).ok().map(str::trim) else {
                    return false;
                };
                let Some(path) = url_path(url) else {
                    return false;
                };
                let other = match dir {
                    Direction::ToHost => shares::to_host(shares, &path),
                    Direction::ToGuest => shares::to_guest(shares, &path),
                };
                match other {
                    Some(p) => {
                        *d = path_url(&p).into_bytes();
                        true
                    }
                    None => false,
                }
            });
            (!i.types.is_empty()).then_some(i)
        })
        .collect()
}

/// The state machine of the rule that the clipboard moves only while a
/// session window is key.
#[derive(Debug, Default)]
pub struct Sync {
    shares: Vec<Share>,
    key: bool,
    /// The latest host content and its change count.
    host: Option<(u64, Vec<Item>)>,
    /// The host change count that the guest has.
    host_sent: Option<u64>,
    guest_count: Option<u64>,
    /// What went to the guest last: its echo as a guest change is not a
    /// change.
    last_sent: Option<Vec<Item>>,
    /// What was set on the host last: its echo as a host change is not a
    /// change.
    last_set: Option<Vec<Item>>,
}

impl Sync {
    pub fn new(shares: Vec<Share>) -> Self {
        Sync {
            shares,
            ..Default::default()
        }
    }

    pub fn is_key(&self) -> bool {
        self.key
    }

    /// A session window became key (`true`) or resigned (`false`).
    pub fn on_key(&mut self, key: bool) -> Vec<Action> {
        self.key = key;
        if !key {
            return vec![Action::Nothing];
        }
        match &self.host {
            Some((count, items)) if self.host_sent != Some(*count) => {
                let (count, items) = (*count, items.clone());
                vec![self.send_guest(count, &items)]
            }
            _ => vec![Action::Nothing],
        }
    }

    /// The host pasteboard changed: `count` is its change count.
    pub fn on_host_change(&mut self, count: u64, items: Vec<Item>) -> Vec<Action> {
        if self.host.as_ref().is_some_and(|(c, _)| *c == count) {
            return vec![Action::Nothing];
        }
        let echo = self.last_set.as_ref() == Some(&items);
        self.host = Some((count, items.clone()));
        if echo {
            self.host_sent = Some(count);
            return vec![Action::Nothing];
        }
        if !self.key {
            return vec![Action::Nothing];
        }
        vec![self.send_guest(count, &items)]
    }

    /// The guest pasteboard changed.
    pub fn on_guest_change(&mut self, count: u64, items: Vec<Item>) -> Vec<Action> {
        if self.guest_count == Some(count) {
            return vec![Action::Nothing];
        }
        self.guest_count = Some(count);
        if !self.key {
            return vec![Action::Nothing];
        }
        if self.last_sent.as_ref() == Some(&items) {
            return vec![Action::Nothing];
        }
        match prepare(&items) {
            Err(badge) => vec![Action::Refuse(badge)],
            Ok(kept) => {
                let kept = translate(kept, &self.shares, Direction::ToHost);
                if kept.is_empty() {
                    return vec![Action::Nothing];
                }
                self.last_set = Some(kept.clone());
                vec![Action::SetHost(Payload { items: kept })]
            }
        }
    }

    fn send_guest(&mut self, count: u64, items: &[Item]) -> Action {
        self.host_sent = Some(count);
        match prepare(items) {
            Err(badge) => Action::Refuse(badge),
            Ok(kept) => {
                let kept = translate(kept, &self.shares, Direction::ToGuest);
                if kept.is_empty() {
                    return Action::Nothing;
                }
                self.last_sent = Some(kept.clone());
                Action::SendToGuest(Payload { items: kept })
            }
        }
    }
}

